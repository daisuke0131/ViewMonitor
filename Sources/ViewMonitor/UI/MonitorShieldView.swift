import UIKit

/// 計測中にアプリ本体へのタッチを遮る透明ビュー。
///
/// 計測ボタンに覆われていない領域へのタップ・スクロール・エッジスワイプが
/// アプリ側に届くと、ボタンの誤発火だけでなく、画面遷移で計測状態ごと
/// 破棄されてしまう(遷移検知の reload が実行ボタンを OFF の新品に差し替える)。
///
/// rootView 直下・計測 UI より背面に挟み、届いたタッチをすべて吸収する。
/// 計測ボタン・InfoView・実行ボタンは必ずこの盾より前面(rootView 直下)に
/// 置くこと。背面のビューへ選択的にタッチを通す作りにはできない:
/// ヒットテストの引き直しは経路上の `_UIHostingView.hitTest`(SwiftUI 独自
/// 実装)を通るが、これは純粋関数ではなく、同じ点への連続呼び出しで異なる
/// 結果を返すことがある(実機で1回目は配下の計測ボタン、2回目は自分自身を
/// 返し、タッチが盾に吸収された)。
final class MonitorShieldView: UIView {}
